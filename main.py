    print(f"Усього слів: {len(всі_слова)}, унікальних: {len(словник_частот)}")

    # Безпечне отримання частоти: .get() не падає, якщо ключа немає
    print(f"Частота слова 'python': {словник_частот.get('python', 0)}")
    print(f"Частота слова 'java' (його немає в тексті): {словник_частот.get('java', 0)}\n")

    # Сортування за ключем (алфавіт)
    сортування_алфавіт = sorted(словник_частот.items())
    print("Сортування за алфавітом (перші 8 слів):")
    for слово, кількість in сортування_алфавіт[:8]:
        print(f"  {слово}: {кількість}")

    # Сортування за спаданням частоти (при однакових частотах - за алфавітом)
    сортування_частота = sorted(словник_частот.items(), key=lambda пара: (-пара[1], пара[0]))
    print("\nНайпопулярніші слова (топ-8):")
    for слово, кількість in сортування_частота[:8]:
        print(f"  {слово}: {кількість}")

    # Dict comprehension: залишаємо тільки слова з частотою не нижче порога
    популярні_слова = {слово: к for слово, к in словник_частот.items() if к >= ПОРІГ}
    print(f"\nСлова, що зустрічаються {ПОРІГ} або більше разів ({len(популярні_слова)} шт.):")
