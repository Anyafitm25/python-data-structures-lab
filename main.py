ПОРІГ = 2                          # мінімальна частота для відбору "популярних" слів
ФАЙЛ_ТЕКСТУ = "text.txt"           # вхідний файл (UTF-8)
ФАЙЛ_РЕЗУЛЬТАТУ = "task3_result.txt"


def порахувати_частоти(елементи):
    """Рахує, скільки разів зустрічається кожен елемент (без Counter)."""
    частоти = {}
    for елемент in елементи:
        частоти[елемент] = частоти.get(елемент, 0) + 1
    return частоти


