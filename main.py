# =====================================================================
def run_task_4():
    print("=== Завдання 4. Робота з множинами ===")
    
    # Логи відвідування сайту двома групами (є повтори)
    юзери_група_а = ["user1", "user2", "user3", "user1", "user4", "user2"]
    юзери_група_б = ["user3", "user4", "user5", "user6", "user4"]
    юзери_маленька_група = ["user1", "user2"]
    
    # Перетворюємо у множини, щоб прибрати дублікати
    множина_а = set(юзери_група_а)
    множина_б = set(юзери_група_б)
    множина_с = set(юзери_маленька_група)
    
    print(f"Унікальні юзери А: {множина_а}")
    print(f"Унікальні юзери Б: {множина_б}")
    print(f"Маленька множина С: {множина_с}\n")
    
    # Математичні операції над множинами
    print(f"Перетин (хто є і там, і там): {множина_а.intersection(множина_б)}")
    print(f"Об'єднання (всі унікальні разом): {множина_а.union(множина_б)}")
    print(f"Симетрична різниця (хто лише в одній групі): {множина_а.symmetric_difference(множина_б)}")
    
    # Перевірка підмножини
    print(f"\nПеревірка підмножин:")
    print(f"  Чи є С підмножиною А (С <= А)? {множина_с.issubset(множина_а)}")
    print(f"  Чи є Б підмножиною А (Б <= А)? {множина_б.issubset(множина_а)}\n")


