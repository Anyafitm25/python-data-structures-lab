def run_task_5():
    print("=== Завдання 5. Експерименти з часом ===")
    
    розміри = [100, 1000, 10000]
    таблиця_результатів = {}
    
    for n in розміри:
        тест_список = list(range(n))
        тест_множина = set(тест_список)
        тест_словник = {i: i for i in тест_список}
        
        шукане_число = n + 5  # Число, якого точно немає в базі
        ітерації = 1000       # Скільки разів повторюємо для точності
        
        # 1. Заміряємо час пошуку в списку
        час_список = timeit.timeit(lambda: шукане_число in тест_список, number=ітерації) / ітерації * 1_000_000
        # 2. Заміряємо час пошуку в множині
        час_множина = timeit.timeit(lambda: шукане_число in тест_множина, number=ітерації) / ітерації * 1_000_000
        # 3. Заміряємо час пошуку в словнику
        час_словник = timeit.timeit(lambda: шукане_число in тест_словник, number=ітерації) / ітерації * 1_000_000
        
        # 4. Створюємо великий список із дублікатами для перевірки збору унікальних
        вхідні_дублікати = list(range(n)) * 2
        
        def збір_через_список():
            результат = []
            for елемент in вхідні_дублікати:
                if елемент not in результат:
                    результат.append(елемент)
                    
        def збір_через_множину():
            результат = set()
            for елемент in вхідні_дублікати:
                результат.add(елемент)
                
        час_збір_список = timeit.timeit(збір_через_список, number=3) / 3 * 1_000_000
        час_збір_множина = timeit.timeit(збір_через_множину, number=3) / 3 * 1_000_000
        
        таблиця_результатів[n] = (час_список, час_множина, час_словник, час_збір_список, час_збір_множина)
        
    # Гарний вивід результатів експерименту
    print(f"{'N':<7} | {'Пошук у List':<14} | {'Пошук у Set':<14} | {'Пошук у Dict':<14} | {'Збір у List':<14} | {'Збір у Set':<14}")
    print("-" * 88)
    for n in розміри:
        рез = таблиця_результатів[n]
        print(f"{n:<7} | {рез[0]:<14.4f} | {рез[1]:<14.4f} | {рез[2]:<14.4f} | {рез[3]:<14.2f} | {рез[4]:<14.2f}")


