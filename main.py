    print(f"Елемент з кінця (індекс -1): {номера[-1]}\n")
    
    # Робимо три різних зрізи, як просив викладач
    зріз_простий = номера[1:5]
    зріз_із_кроком = номера[:8:2]  # крок 2
    зріз_реверс = номера[::-1]     # перевертаємо
    
    print(f"Зріз [1:5]: {зріз_простий} (Новий ID: {id(зріз_простий)})")
    print(f"Зріз з кроком 2 [:8:2]: {зріз_із_кроком} (Новий ID: {id(зріз_із_кроком)})")
    print(f"Перевернутий список [::-1]: {зріз_реверс} (Новий ID: {id(зріз_реверс)})\n")
    
    # Змінюємо список на місці (мутації)
    номера.append(110)  # додаємо в кінець
    print(f"Додали 110 в кінець: {номера} (Довжина: {len(номера)})")
    
    номера.insert(0, 5)  # додаємо на початок
    print(f"Додали 5 на початок: {номера} (Довжина: {len(номера)})")
    
    номера.remove(50)  # видаляємо число 50
    print(f"Видалили число 50: {номера} (Довжина: {len(номера)})")
    
    # Замінюємо шматочок списку іншими числами
    номера[1:3] = [15, 25]
    print(f"Після заміни шматочка [1:3]: {номера} (Довжина: {len(номера)})")
    print(f"ID оригінального списку не змінився: {id(номера)}\n")


