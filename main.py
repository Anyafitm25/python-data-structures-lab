# ЗАВДАННЯ 5. Алгоритмічна складність (бенчмарки)
# =====================================================================
def заміряти(функція, number, repeat=5):
    """Повертає (середній час одного виклику в секундах, розкид max-min)."""
    спроби = [t / number for t in timeit.repeat(функція, number=number, repeat=repeat)]
    середнє = sum(спроби) / len(спроби)
    розкид = max(спроби) - min(спроби)
    return середнє, розкид


def run_task_5():
    print("=== Завдання 5. Експерименти з часом ===")
    print("Метод: timeit.repeat, 5 повторів, наводиться середнє ± розкид (max-min)\n")

    розміри = [100, 1000, 10000]
    пошук = {}   # n -> (список, множина, словник), кожен елемент (середнє, розкид) в мкс
    збір = {}    # n -> (список, множина, dict.fromkeys), у мс

    for n in розміри:
        тест_список = list(range(n))
        тест_множина = set(тест_список)
        тест_словник = {i: i for i in тест_список}
        шукане = n + 5  # гарантовано відсутнє число (найгірший випадок для списку)
        ітерації = 1000

        рез_список = заміряти(lambda: шукане in тест_список, ітерації)
        рез_множина = заміряти(lambda: шукане in тест_множина, ітерації)
        рез_словник = заміряти(lambda: шукане in тест_словник, ітерації)
        пошук[n] = tuple((с * 1_000_000, р * 1_000_000) for с, р in (рез_список, рез_множина, рез_словник))

        вхідні_дані = list(range(n)) * 2  # кожне значення двічі

        def збір_через_список():
            результат = []
            for елемент in вхідні_дані:
                if елемент not in результат:
                    результат.append(елемент)
            return результат

        def збір_через_множину():
            бачили = set()
            for елемент in вхідні_дані:
                бачили.add(елемент)
            return бачили

        def збір_через_dict():
            return list(dict.fromkeys(вхідні_дані))  # зберігає порядок вставки

        рез_збір_список = заміряти(збір_через_список, 1)
        рез_збір_множина = заміряти(збір_через_множину, 10)
        рез_збір_dict = заміряти(збір_через_dict, 10)
        збір[n] = tuple((с * 1000, р * 1000) for с, р in (рез_збір_список, рез_збір_множина, рез_збір_dict))

    print("Таблиця 1. Перевірка наявності відсутнього елемента, мкс (мікросекунди)")
    print(f"{'n':<8}| {'list':<22}| {'set':<22}| {'dict':<22}")
    print("-" * 76)
    for n in розміри:
        л, м, с = пошук[n]
        print(f"{n:<8}| {л[0]:>9.3f} ± {л[1]:<9.3f}| {м[0]:>9.3f} ± {м[1]:<9.3f}| {с[0]:>9.3f} ± {с[1]:<9.3f}")

    print("\nТаблиця 2. Збір унікальних значень за один прохід (2n елементів), мс (мілісекунди)")
    print(f"{'n':<8}| {'list + перевірка':<22}| {'set.add':<22}| {'dict.fromkeys':<22}")
