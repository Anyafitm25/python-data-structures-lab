def розпакувати_запис(запис):
    """Приймає один кортеж-запис і повертає його поля через розпакування."""
    код, назва, кількість, ціна, оцінки = запис
    return код, назва, кількість, ціна, оцінки


def загальна_вартість(каталог):
    """Приймає список кортежів і рахує загальну вартість товарів на складі (грн)."""
    сума = 0.0
    for запис in каталог:
        _, _, кількість, ціна, _ = запис
        сума += кількість * ціна
    return сума


